# 3. 词级 — 手动设定超参数
# ============================================================
def word_manual_train():
    """
    词级 + 手动调参训练

    策略：用 jieba 分词后训练，超参数与字符级手动调参一致。

    词级 vs 字符级：
        - 词级：jieba 分词 → "房山 纯新盘 绿地 新都会 国际 花都" → 有完整语义
        - 字符级：list 拆字 → "房 山 纯 新 盘 绿 地 新 都 会" → 依赖子词建模
        - 词级的优势：语义完整，但可能丢失子词信息
        - 实践建议：两种都训练，对比结果选最优
    """
    print("=" * 60)
    print("【词级 — 手动调参】开始训练...")
    print("=" * 60)

    # ========================================================
    # 3.1 模型训练
    # ========================================================
    model = fasttext.train_supervised(
        input=config.process_word_train_datapath,
        dim=100,
        epoch=10,
        minn=1,
        maxn=4,
    )

    # ========================================================
    # 3.2 保存模型
    # ========================================================
    model.save_model(config.model_word_manual_train)

    # ========================================================
    # 3.3 评估
    # ========================================================
    result = model.test(config.process_word_test_datapath)
    print(f"词级_手动调参_评估结果：{result}")
    # 词级_手动调参_评估结果：(10000, 0.9176, 0.9176)

    # ========================================================
    # 3.4 子词示例：观察中文词在词级模式下的子词切分
    # ========================================================
    # 输入 "人工智能"（4 个字），minn=1, maxn=4
    # 子词包括：<人工智能>, 人, 工, 智, 能, 人工, 工智, 智能, ...
    print("子词示例：", model.get_subwords("人工智能"))


