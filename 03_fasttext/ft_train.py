# -*- coding: utf-8 -*-
"""
FastText 文本分类训练模块
==========================

功能：使用 Facebook 开源的 FastText 对中文新闻标题进行多分类训练。

完整流程：
    1. 数据预处理（data_preprocessing.py）：将原始 txt 转为 FastText 格式
    2. 模型训练（本文件）：4 种策略（字符级/词级 × 手动调参/自动调参）
    3. 模型评估：test() 返回 样本数、精确率、召回率
    4. 模型保存：save_model() 持久化到磁盘

【FastText 简介】
    FastText 是 Facebook 在 2016 年开源的文本分类与词向量训练工具，核心思想是
    "子词（sub-word）建模"：把一个词拆成多个字符级 n-gram，用这些 n-gram 的
    向量之和来表示这个词。这样做的好处是：
    1. 训练速度极快（比深度学习快几个数量级）
    2. 能处理未登录词（OOV）：通过子词拼出未知词的向量
    3. 对中文特别友好：中文的"字"天然就是有意义的子词单元

【FastText 数据格式要求】
    每行一条样本，格式为：
        __label__类别名 空格分隔的文本
    示例：
        __label__finance 沪 深 两 市 全 面 反 弹
        __label__sports 世 界 杯 决 赛 明 日 开 战

    注意：
    - 标签前缀必须是 __label__（双下划线）
    - 英文文本不需要额外处理（天然空格分隔）
    - 中文文本需要预处理：分词或分字，用空格连接

【4 种训练策略对比】
                        | 字符级（char）      | 词级（word）
    --------------------|---------------------|---------------------
    手动调参（manual）   | char_manual_train() | word_manual_train()
    自动调参（auto）     | char_auto_train()   | word_auto_train()

    字符级：将文本拆成单字（如 "今 天 天 气"），配合 FastText 子词建模效果最好
    词级：  用 jieba 分词（如 "今天 天气"），保留完整语义但可能丢失子词信息

依赖：
    - fasttext：Facebook 开源文本分类库（pip install fasttext）
    - config.py：项目路径配置
"""

import fasttext
from config import Config

# ============================================================
# 加载配置
# ============================================================
config = Config()


# ============================================================
# 1. 字符级 — 手动设定超参数
# ============================================================
def char_manual_train():
    """
    字符级 + 手动调参训练

    策略：根据经验手动设定 dim、epoch、minn、maxn 等超参数

    FastText 字符级预处理：
        原始文本 "沪深两市反弹" → 预处理后 "沪 深 两 市 反 弹"
        每个字之间用空格分隔，FastText 会自动抽取 n-gram 子词
    """
    print("=" * 60)
    print("【字符级 — 手动调参】开始训练...")
    print("=" * 60)

    # ========================================================
    # 1.1 模型训练：fasttext.train_supervised()
    # ========================================================
    #
    # train_supervised() 是 FastText 有监督分类的核心 API，
    # 底层基于 Skip-Gram 词向量 + Hierarchical Softmax 分类器。
    #
    # --- 必选参数 ---
    # input : str
    #     训练数据文件路径，格式为每行一条 "__label__X 文本"。
    #     必须是经过 data_preprocessing.py 预处理后的文件。
    #
    # --- 核心超参数 ---
    # dim : int, default=100
    #     词向量维度。每个词/子词被映射为一个 dim 维的向量。
    #     - 越大：表示能力越强，但训练慢、容易过拟合
    #     - 越小：训练快、泛化好，但可能欠拟合
    #     - 推荐范围：50~300（数据量 >10w 时用 200~300）
    #     - 数据量约 18w 条，用 100 足够
    #
    # epoch : int, default=5
    #     训练轮数（遍历整个数据集的次数）。
    #     - 过小：欠拟合，模型没学够
    #     - 过大：过拟合，训练集效果好但验证集差
    #     - 推荐范围：5~50（数据量小用大值，数据量大用小值）
    #     - 数据量 18w 条，设 10 轮即可，50 轮跑太久且收益递减
    #
    # lr : float, default=0.1
    #     学习率（Learning Rate）。控制每次参数更新的步长。
    #     - 过大：震荡不收敛
    #     - 过小：收敛慢
    #     - 推荐范围：0.05~1.0
    #     - 这里使用默认值 0.1
    #
    # minn : int, default=0
    #     最小 n-gram 长度（字符数）。
    #     - 0：不使用子词（相当于退化为普通的词向量）
    #     - 1：包含单字（对中文很重要！）
    #     - 2：不包含单字
    #     - 中文场景建议设为 1，因为单个汉字本身就是有意义的语义单元
    #
    # maxn : int, default=0
    #     最大 n-gram 长度（字符数）。
    #     - 0：不使用子词
    #     - 3~6：推荐范围
    #     - 4：能覆盖大多数中文词（如 "人工智能" 是 4 个字）
    #     - 越大：子词越多，模型越大，训练越慢
    #     - 注意：minn 和 maxn 同时 >0 才启用子词功能
    #
    # minCount : int, default=1
    #     词频阈值。出现次数少于此值的词会被忽略。
    #     - 1：保留所有词
    #     - 5：过滤掉出现少于 5 次的罕见词
    #     - 增大可减少噪声、缩小模型体积
    #
    # wordNgrams : int, default=1
    #     词级 n-gram 的最大长度。
    #     - 1：只用单个词（unigram）
    #     - 2：同时用单个词和相邻两个词的组合（bigram），能捕捉短语信息
    #     - 推荐：分类任务设为 2，能捕捉 "人工智能 技术" 这样的短语
    #
    # loss : str, default='softmax'
    #     损失函数类型。
    #     - 'softmax'：标准多分类，类别少（<100）时用
    #     - 'hs'：Hierarchical Softmax，类别多时更快
    #     - 'ns'：Negative Sampling，类别极多时用
    #     - 'ova'：One-vs-All，多标签分类用
    #
    # thread : int, default=12
    #     训练使用的线程数。设为 CPU 核心数可最大化训练速度。
    #
    # verbose : int, default=2
    #     日志详细程度。0=静默，1=进度条，2=每轮输出损失值。

    model = fasttext.train_supervised(
        input=config.process_char_train_datapath,
        dim=100,        # 词向量维度：100 维足够表示 1w 条数据中的语义
        epoch=10,       # 训练轮数：18w 条数据，10 轮足够
        minn=1,         # 最小 n-gram=1：包含单字（对中文至关重要）
        maxn=4,         # 最大 n-gram=4：覆盖大多数中文词的长度
    )

    # ========================================================
    # 1.2 保存模型：model.save_model()
    # ========================================================
    #
    # save_model(path) 将训练好的模型保存为 .bin 二进制文件。
    # 保存内容包括：词向量、n-gram 向量、分类器参数等。
    # 加载用 fasttext.load_model(path)。
    model.save_model(config.model_char_manual_train)

    # ========================================================
    # 1.3 模型评估：model.test()
    # ========================================================
    #
    # test(file_path) 在测试集上评估模型性能。
    #
    # 参数：
    #     file_path : str — 测试集文件路径，格式与训练数据一致
    #
    # 返回值：元组 (N, P@1, R@1)
    #     N    : int   — 测试集样本总数
    #     P@1  : float — Top-1 精确率（Precision@1）
    #                      含义：预测为某类的样本中，真正是该类的比例
    #     R@1  : float — Top-1 召回率（Recall@1）
    #                      含义：某类样本中，被正确预测的比例
    #     FastText 的 P@1 == R@1，因为每个样本只预测一个类别
    #
    #     补充：test_label(file_path) 可以获取每个类别的详细指标
    result = model.test(config.process_char_test_datapath)
    print(f"字符级_手动调参_评估结果：{result}")
    # 字符级_手动调参_评估结果：(10000, 0.8748, 0.8748)
    # 解释：10000条测试样本，精确率=召回率=87.48%

    # ========================================================
    # 1.4 单条预测：model.predict()
    # ========================================================
    #
    # predict(text, k=1, threshold=0.0)
    #
    # 参数：
    #     text : str — 待预测文本（格式必须与训练数据一致）
    #                   字符级：用空格分隔的单字，如 "房 山 纯 新 盘"
    #                   词级：  用空格分隔的词，如 "房山 纯新盘"
    #     k : int, default=1 — 返回 Top-K 个最可能的类别
    #     threshold : float, default=0.0 — 置信度阈值，低于此值的类别不返回
    #
    # 返回值：元组 (labels, probs)
    #     labels : list[str] — 预测的类别标签列表，如 ['__label__realty']
    #     probs  : list[float] — 对应的概率值，如 [0.95]
    # pred_result = model.predict("房 山 纯 新 盘 绿 地 新 都 会 国 际 花 都 1 1 月 开 盘")
    # print(f"预测结果：{pred_result}")
    # 输出示例：(('__label__realty',), array([0.95123456]))

    # ========================================================
    # 1.5 查看词汇表：model.words
    # ========================================================
    #
    # words 属性：返回模型中所有词的列表（list[str]）。
    # 只包含训练时出现过的词，不包含子词（n-gram）。
    # 常用于：检查词汇表大小、查看有哪些词被模型学习了。
    words = model.words
    print(f"词汇表类型：{type(words)}")     # <class 'list'>
    print(f"词汇表大小：{len(words)}")      # 例如：5000
    print(f"前10个词：{words[:10]}")

    # ========================================================
    # 1.6 查看子词：model.get_subwords()
    # ========================================================
    #
    # get_subwords(word) 返回一个词的所有子词（n-gram）列表。
    #
    # 子词 = 原词 + 所有的 n-gram（其中 minn <= n <= maxn）
    #
    # 示例（minn=1, maxn=4）：
    #     输入词 "ab"（2个字）
    #     子词 = ['<ab>', 'a', 'b', 'ab', '<a', 'ab>']
    #     解释：
    #       - '<ab>'：整个词（用尖括号包裹，表示完整词）
    #       - 'a', 'b'：1-gram（单字）
    #       - 'ab'：2-gram（两个连续字）
    #       - '<a'：前缀 2-gram（开头标记 + 第一个字）
    #       - 'ab>'：后缀 2-gram（最后两个字 + 结尾标记）
    #
    # 补充：FastText 用 '<' 和 '>' 作为词的边界标记，
    #       这样 "<ab" 和 "ab>" 分别表示词首和词尾的子词，
    #       能区分同一 n-gram 在词中不同位置的含义。
    print("子词示例：", model.get_subwords("ab"))

    # ========================================================
    # 1.7 查看词向量维度：model.get_dimension()
    # ========================================================
    #
    # get_dimension() 返回词向量的维度（即训练时设定的 dim 参数值）。
    # 用于确认模型配置是否正确。
    print("词向量维度：", model.get_dimension())  # 100


