# 2. 字符级 — 自动调参
# ============================================================
def char_auto_train():
    """
    字符级 + 自动调参训练

    策略：使用 FastText 内置的 autotune 功能，自动搜索最优超参数组合。

    自动调参 vs 手动调参：
        - 手动：凭经验设参数，快速但可能不是最优
        - 自动：FastText 自动尝试多组参数，在验证集上选最优，省心但耗时
        - 推荐：先用自动调参找到大致方向，再手动微调
    """
    print("=" * 60)
    print("【字符级 — 自动调参】开始训练...")
    print("=" * 60)

    # ========================================================
    # 2.1 自动调参训练
    # ========================================================
    #
    # train_supervised() 的自动调参参数：
    #
    # autotuneValidationFile : str
    #     验证集文件路径。自动调参时，每组参数在验证集上评估，
    #     选 F1 最高的那组作为最终参数。
    #     必须提供，否则无法自动调参。
    #
    # autotuneDuration : int
    #     自动调参的最大时长（秒）。
    #     - 3*60 = 180 秒 = 3 分钟
    #     - 时间越长，尝试的参数组合越多，越可能找到更优解
    #     - 但收益递减：前 3 分钟收益最大，之后越来越小
    #     - 推荐：开发阶段设 60~300 秒，正式训练设 600~3600 秒
    #
    # autotuneModelSize : str, optional
    #     约束模型大小，用于控制最终模型文件体积。
    #     - 不设：不限制模型大小
    #     - "1M"：限制模型约 1MB
    #     - "10M"：限制模型约 10MB
    #     - 适用于需要部署到移动端或边缘设备的场景
    #
    # autotunePredictions : bool, default=False
    #     是否在自动调参结束后输出预测结果。
    #
    # seed : int, default=0
    #     随机种子。固定后可复现训练结果。
    #     设为 115（或其他任意整数）保证每次运行结果一致。
    #
    # verbose : int, default=2
    #     日志详细程度。自动调参时建议设 3 以上，
    #     可以看到每组参数的具体得分。

    model = fasttext.train_supervised(
        input=config.process_char_train_datapath,
        autotuneValidationFile=config.process_char_dev_datapath,  # 验证集
        autotuneDuration=3 * 60,  # 自动调参时长：3 分钟
        seed=115,                 # 随机种子：保证可复现
        verbose=3,                # 日志级别：3 可看到每组参数得分
    )

    # ========================================================
    # 2.2 保存模型
    # ========================================================
    model.save_model(config.model_char_auto_train)

    # ========================================================
    # 2.3 评估
    # ========================================================
    result = model.test(config.process_char_test_datapath)
    print(f"字符级_自动调参_评估结果：{result}")
    # 字符级_自动调参_评估结果：(10000, 0.9218, 0.9218)

    # ========================================================
    # 2.4 单条预测
    # ========================================================
    # pred_result = model.predict("房 山 纯 新 盘 绿 地 新 都 会 国 际 花 都 1 1 月 开 盘")
    # print(f"预测结果：{pred_result}")


